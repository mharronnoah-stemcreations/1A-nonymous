-- 1. Create the messages table
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  content text not null,
  prompt text default 'Send me anonymous messages!',
  recipient text default 'toad',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Enable Row Level Security (RLS)
alter table public.messages enable row level security;

-- 3. Policy: Allow anyone (anonymous users) to send/insert messages
drop policy if exists "Allow anonymous message inserts" on public.messages;
create policy "Allow anonymous message inserts"
  on public.messages
  for insert
  with check (true);

-- 4. Policy: Allow anyone to read messages (for the public Toad inbox)
drop policy if exists "Allow public message reads" on public.messages;
create policy "Allow public message reads"
  on public.messages
  for select
  using (true);

